"""Experiment 16 — Rotation-Invariant 3D Retrieval via LLM Space Alignment

Motivation
----------
Experiments 11/11b used ImageBind's contrastive space as the alignment target.
Experiments 14/15 used sentence-transformer embeddings (all-mpnet-base-v2).

This experiment aligns RISA embeddings into a *generative LLM's* token space
(LLaMA-2-7B), using per-shape descriptions generated by LLaVA from rendered
views. The key claims:

  1. LLaMA's token space captures richer geometric language than contrastive
     embeddings — enabling more precise text-to-3D retrieval.
  2. RISA's rotation invariance is preserved after alignment — shapes at any
     orientation retrieve the same set of text-similar shapes.
  3. At query time, ANY free-text query (not just class names or templates)
     can retrieve 3D shapes by encoding the query through the frozen LLaMA
     text encoder and doing cosine similarity in the shared 512-d space.

Architecture
------------
    3D branch:
        point cloud [N, 3]
          → RISA encoder with fps_K prior  (fine-tuned, low lr)
          → z_risa  [encoding_out_dim]
          → ProjectionMLP (encoding_out_dim → LLM_DIM=512)
          → z_3d   [512]  (L2-normalised)

    Text branch (frozen):
        description text
          → LLaMA-2-7B (4-bit, frozen)
          → last hidden state, mean-pooled  [4096]
          → Linear projection (PCA-whitened, frozen)  [512]
          → z_text  [512]  (L2-normalised)

    Loss: symmetric InfoNCE(z_3d, z_text)

Text embeddings are pre-computed by exp16_generate_llm_descriptions.py
and loaded from:
    outputs/text_cache/{dataset}_{split}_llm_emb.pt

Usage
-----
  # Step 1 (once): generate descriptions and LLM embeddings
  python experiments/exp16_generate_llm_descriptions.py --dataset shapenet

  # Step 2: train
  python experiments/exp16_train.py

  # Custom settings:
  python experiments/exp16_train.py \\
      --dataset shapenet \\
      --K 256 \\
      --epochs 50 \\
      --batch_size 128 \\
      --lr_risa 1e-6 \\
      --lr_proj 1e-4 \\
      --warmup_epochs 5

  # Resume:
  python experiments/exp16_train.py \\
      --resume outputs/checkpoints/exp16_fps_K_best.pt
"""

